package com.watube.yard.cast

import com.watube.yard.api.obj.Subtitle
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The TV plays what the phone chose: audio track, quality and subtitles, out of a master shaped
 * like YouTube's (seen on a real receiver): every audio track DEFAULT=NO, dubbed ones first.
 */
class StolmChoicesTest {
    private val master = """
        #EXTM3U
        #EXT-X-INDEPENDENT-SEGMENTS
        #EXT-X-MEDIA:URI="a/ar",TYPE=AUDIO,GROUP-ID="234",LANGUAGE="ar",NAME="العربية - dubbed",YT-EXT-XTAGS="Cg8KBWFjb250EgZkdWJiZWQKCgoEbGFuZxICYXI",DEFAULT=NO,AUTOSELECT=YES
        #EXT-X-MEDIA:URI="a/fr",TYPE=AUDIO,GROUP-ID="234",LANGUAGE="fr",NAME="Français - dubbed",YT-EXT-XTAGS="Cg8KBWFjb250EgZkdWJiZWQKCgoEbGFuZxICZnI",DEFAULT=NO,AUTOSELECT=YES
        #EXT-X-MEDIA:URI="a/en",TYPE=AUDIO,GROUP-ID="234",LANGUAGE="en-US",NAME="American English - original",YT-EXT-XTAGS="ChEKBWFjb250EghvcmlnaW5hbAoNCgRsYW5nEgVlbi1VUw",DEFAULT=NO,AUTOSELECT=YES
        #EXT-X-MEDIA:URI="s/fr",TYPE=SUBTITLES,GROUP-ID="vtt",LANGUAGE="fr",NAME="Français",DEFAULT=NO,AUTOSELECT=YES
        #EXT-X-STREAM-INF:BANDWIDTH=1355489,CODECS="avc1.4D401E,mp4a.40.2",RESOLUTION=854x480,AUDIO="234",SUBTITLES="vtt",CLOSED-CAPTIONS=NONE
        v/480
        #EXT-X-STREAM-INF:BANDWIDTH=2316916,CODECS="avc1.4D401F,mp4a.40.2",RESOLUTION=1280x720,AUDIO="234",SUBTITLES="vtt",CLOSED-CAPTIONS=NONE
        v/720
        #EXT-X-STREAM-INF:BANDWIDTH=4699793,CODECS="avc1.640028,mp4a.40.2",RESOLUTION=1920x1080,AUDIO="234",SUBTITLES="vtt",CLOSED-CAPTIONS=NONE
        v/1080
    """.trimIndent()

    private val subtitles = listOf(
        Subtitle("https://www.youtube.com/api/timedtext?lang=fr&fmt=ttml", "application/ttml+xml", "Français", "fr", false),
        Subtitle("https://www.youtube.com/api/timedtext?lang=en&kind=asr&fmt=ttml", "application/ttml+xml", "English", "en", true)
    )

    private fun audioOf(selected: String) = selected.lines().filter { "TYPE=AUDIO" in it }
    private fun variantsOf(selected: String) = selected.lines().filter { !it.startsWith("#") && it.isNotBlank() }

    @Test
    fun theOriginalWhenThePhoneChoseNothing() {
        // the receiver used to play the first track listed, a dubbed one
        val audio = audioOf(HlsMaster.select(master, StolmChoices()))
        assertEquals(1, audio.size)
        assertTrue(audio.single(), "LANGUAGE=\"en-US\"" in audio.single())
        assertTrue(audio.single(), "DEFAULT=YES" in audio.single())
    }

    @Test
    fun theDubbedTrackThePhonePlays() {
        val audio = audioOf(HlsMaster.select(master, StolmChoices(audioLanguage = "fr", dubbed = true)))
        assertEquals(listOf("fr"), audio.map { it.substringAfter("LANGUAGE=\"").substringBefore('"') })
    }

    @Test
    fun theOriginalWhenTheLanguageIsMissing() {
        val audio = audioOf(HlsMaster.select(master, StolmChoices(audioLanguage = "ja", dubbed = true)))
        assertTrue("LANGUAGE=\"en-US\"" in audio.single())
    }

    @Test
    fun theChosenQualityOrTheClosestBelow() {
        assertEquals(listOf("v/1080"), variantsOf(HlsMaster.select(master, StolmChoices(maxHeight = 1080))))
        assertEquals(listOf("v/720"), variantsOf(HlsMaster.select(master, StolmChoices(maxHeight = 900))))
        // below every variant: the lowest one
        assertEquals(listOf("v/480"), variantsOf(HlsMaster.select(master, StolmChoices(maxHeight = 144))))
        // automatic: the receiver adapts between all of them
        assertEquals(listOf("v/480", "v/720", "v/1080"), variantsOf(HlsMaster.select(master, StolmChoices())))
    }

    @Test
    fun theMasterKeepsNoSubtitlesOfItsOwn() {
        // the chosen ones go apart, in the LOAD: a dangling SUBTITLES group would break the master
        val selected = HlsMaster.select(master, StolmChoices())
        assertFalse(selected, "TYPE=SUBTITLES" in selected)
        assertFalse(selected, "SUBTITLES=" in selected)
    }

    @Test
    fun aMediaPlaylistIsLeftAsItIs() {
        val media = "#EXTM3U\n#EXTINF:5,\nseg.ts\n#EXT-X-ENDLIST"
        assertEquals(media, HlsMaster.select(media, StolmChoices(audioLanguage = "fr", maxHeight = 480)))
    }

    @Test
    fun optionsListEachTrackOnce() {
        val options = HlsMaster.options(master)
        assertEquals(listOf(1080, 720, 480), options.heights)
        assertEquals(listOf("ar", "fr", "en"), options.audio.map { it.language })
        assertEquals(listOf(false, false, true), options.audio.map { it.isOriginal })
    }

    @Test
    fun thePhoneSubtitlesByLanguageAndKind() {
        val choices = StolmChoices.of("fr-FR", false, Int.MAX_VALUE, "en", autoGeneratedText = true, subtitles)
        assertEquals("fr", choices.audioLanguage)
        assertEquals(subtitles[1], choices.subtitles)
        assertNull(StolmChoices.of(null, false, Int.MAX_VALUE, null, false, subtitles).subtitles)
    }

    @Test
    fun theTrackPickedForTheMenusIsTheOneTheTvPlays() {
        val options = HlsMaster.options(master)
        val choices = StolmChoices(audioLanguage = "fr", dubbed = true, maxHeight = 900)
        assertEquals("fr", HlsMaster.pickAudio(options.audio, choices)?.language)
        assertEquals(720, HlsMaster.pickHeight(options.heights, choices))
        assertNull(HlsMaster.pickHeight(options.heights, StolmChoices()))
    }

    @Test
    fun theTvIsReloadedOnlyWhenItWouldPlaySomethingElse() {
        val options = HlsMaster.options(master)
        // the screen's defaults for a new video ask for the original kind: the French dub stays
        val dubbed = StolmChoices(audioLanguage = "fr", dubbed = true)
        assertTrue(StolmTracks.samePick(options, dubbed, dubbed.copy(dubbed = false)))
        // a 1080p cap pins the variant, no cap lets the TV adapt between all of them
        assertFalse(StolmTracks.samePick(options, StolmChoices(maxHeight = 1080), StolmChoices()))
        assertTrue(StolmTracks.samePick(options, StolmChoices(maxHeight = 900), StolmChoices(maxHeight = 720)))
        assertFalse(StolmTracks.samePick(options, StolmChoices(), StolmChoices(subtitles = subtitles[0])))
        // the master unread: any change counts
        assertFalse(StolmTracks.samePick(HlsOptions.NONE, StolmChoices(maxHeight = 900), StolmChoices(maxHeight = 720)))
    }

    @Test
    fun aSubtitlesChoiceMeansTheSameLanguageOnTheNextVideo() {
        val id = StolmTracks.textIdOf(subtitles[1])
        assertTrue(StolmTracks.isTextTrack(id))
        // the next video lists its subtitles in another order
        assertEquals(subtitles[1], StolmTracks.subtitlesOf(id, subtitles.reversed()))
        assertNull(StolmTracks.subtitlesOf("1:0", subtitles))
        assertNull(StolmTracks.subtitlesOf(null, subtitles))
    }
}
