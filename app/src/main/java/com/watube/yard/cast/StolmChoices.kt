package com.watube.yard.cast

import com.watube.yard.api.obj.Subtitle
import java.util.Base64
import java.util.Locale

// region Stolm
/**
 * What the TV plays of a video, as chosen on the phone: the audio track, the picture height and
 * the subtitles. The phone's choices go along when a cast starts, and a change made in the
 * player options during the cast loads the video again on the TV with the new ones.
 */
internal data class StolmChoices(
    /** Language of the audio track (two letters, like the phone's tracks), null: the original. */
    val audioLanguage: String? = null,
    /** A dubbed track rather than the original one, in [audioLanguage]. */
    val dubbed: Boolean = false,
    /** Highest picture height; [Int.MAX_VALUE] lets the TV adapt to the network. */
    val maxHeight: Int = Int.MAX_VALUE,
    val subtitles: Subtitle? = null
) {
    companion object {
        /**
         * The choices of the phone's player, from its track selection settings: the same ones
         * pick the tracks the phone itself plays.
         */
        fun of(
            audioLanguage: String?,
            dubbed: Boolean,
            maxHeight: Int,
            textLanguage: String?,
            autoGeneratedText: Boolean,
            subtitles: List<Subtitle>
        ) = StolmChoices(
            audioLanguage = audioLanguage?.let(::primaryLanguage),
            dubbed = dubbed,
            maxHeight = maxHeight,
            subtitles = textLanguage?.let { language ->
                val sameLanguage = subtitles.filter {
                    it.url != null && it.code?.let(::primaryLanguage) == primaryLanguage(language)
                }
                sameLanguage.firstOrNull { (it.autoGenerated == true) == autoGeneratedText }
                    ?: sameLanguage.firstOrNull()
            }
        )

        /** "en-US" → "en": the phone's tracks only know the language, not the region. */
        fun primaryLanguage(tag: String) = tag.substringBefore('-').substringBefore('_').lowercase(Locale.ROOT)
    }
}

/** An audio track of a master playlist, as the phone's player options list it. */
internal data class HlsAudio(val language: String?, val isOriginal: Boolean, val name: String?)

/** What a master playlist offers the TV: its audio tracks and its picture heights. */
internal data class HlsOptions(val audio: List<HlsAudio>, val heights: List<Int>) {
    companion object {
        val NONE = HlsOptions(emptyList(), emptyList())
    }
}

/**
 * Narrows a master playlist (castable variants only, see [HlsVariants]) to the [StolmChoices]: one
 * audio track per group, the variants of one height, no subtitles of its own (the chosen ones
 * are sent apart, see [CastSession.load]).
 *
 * YouTube marks none of its audio tracks as the default one, with the dubbed ones first: left
 * as it was, the receiver played whichever came first (Arabic, for instance) whatever the phone
 * played.
 */
internal object HlsMaster {
    private const val MEDIA = "#EXT-X-MEDIA:"
    private val attribute = Regex("([A-Z0-9-]+)=(\"[^\"]*\"|[^,]*)")
    private val subtitlesAttribute = Regex(",SUBTITLES=\"[^\"]*\"")
    private val resolution = Regex("RESOLUTION=\\d+x(\\d+)")

    private class Rendition(val line: String, val group: String?, val audio: HlsAudio, val isDefault: Boolean)

    private fun attributes(line: String): Map<String, String> = attribute.findAll(line.substringAfter(':'))
        .associate { it.groupValues[1] to it.groupValues[2].removeSurrounding("\"") }

    private fun isAudio(line: String) = line.startsWith(MEDIA) && "TYPE=AUDIO" in line

    private fun isSubtitles(line: String) = line.startsWith(MEDIA) && "TYPE=SUBTITLES" in line

    private fun rendition(line: String): Rendition {
        val attributes = attributes(line)
        // YouTube's tags ("acont" original / dubbed / dubbed-auto) are a base64url protobuf
        val tags = attributes["YT-EXT-XTAGS"]?.let { runCatching { String(Base64.getUrlDecoder().decode(it)) }.getOrNull() }
        val describedAs = "${tags.orEmpty()} ${attributes["NAME"].orEmpty()}".lowercase(Locale.ROOT)
        return Rendition(
            line = line,
            group = attributes["GROUP-ID"],
            audio = HlsAudio(
                language = attributes["LANGUAGE"]?.let(StolmChoices::primaryLanguage),
                isOriginal = "dubbed" !in describedAs,
                name = attributes["NAME"]
            ),
            isDefault = attributes["DEFAULT"] == "YES"
        )
    }

    private fun heightOf(streamInf: String) = resolution.find(streamInf)?.groupValues?.get(1)?.toIntOrNull()

    fun options(master: String): HlsOptions {
        val lines = master.lines()
        return HlsOptions(
            audio = lines.filter(::isAudio).map { rendition(it).audio }.distinct(),
            heights = lines.filter { it.startsWith(HlsVariants.STREAM_INF) }.mapNotNull(::heightOf)
                .distinct().sortedDescending()
        )
    }

    /** The audio track the TV plays among [audio]: the phone's language and kind, else the original. */
    fun pickAudio(audio: List<HlsAudio>, choices: StolmChoices): HlsAudio? {
        val wanted = choices.audioLanguage
        val sameLanguage = audio.filter { wanted != null && it.language == wanted }
        return sameLanguage.firstOrNull { it.isOriginal != choices.dubbed }
            ?: sameLanguage.firstOrNull()
            ?: audio.firstOrNull { it.isOriginal }
            ?: audio.firstOrNull()
    }

    /** The height the TV plays: the highest up to the chosen one, null for all (automatic). */
    fun pickHeight(heights: List<Int>, choices: StolmChoices): Int? {
        if (choices.maxHeight == Int.MAX_VALUE || heights.isEmpty()) return null
        return heights.filter { it <= choices.maxHeight }.maxOrNull() ?: heights.min()
    }

    fun select(master: String, choices: StolmChoices): String {
        if (!master.contains(HlsVariants.STREAM_INF)) return master
        val lines = master.lines()
        val renditions = lines.filter(::isAudio).map(::rendition)
        // the group of a variant and its audio tracks go together: one track kept in each group
        val keptAudio = renditions.groupBy { it.group }.values.mapNotNull { group ->
            val picked = pickAudio(group.map { it.audio }, choices)
            group.firstOrNull { it.audio == picked } ?: group.firstOrNull { it.isDefault }
        }.map { it.line }.toSet()
        val height = pickHeight(lines.filter { it.startsWith(HlsVariants.STREAM_INF) }.mapNotNull(::heightOf), choices)

        val kept = ArrayList<String>(lines.size)
        var dropUri = false
        for (line in lines) {
            when {
                isAudio(line) -> if (line in keptAudio) kept += asDefault(line)
                isSubtitles(line) -> Unit
                line.startsWith(HlsVariants.STREAM_INF) -> {
                    dropUri = height != null && heightOf(line) != height
                    if (!dropUri) kept += line.replace(subtitlesAttribute, "")
                }
                // the URI line of the variant above
                line.isNotBlank() && !line.startsWith("#") -> {
                    if (!dropUri) kept += line
                    dropUri = false
                }
                else -> kept += line
            }
        }
        return kept.joinToString("\n")
    }

    private fun asDefault(line: String) = line
        .replace("DEFAULT=NO", "DEFAULT=YES")
        .let { if ("DEFAULT=" in it) it else "$it,DEFAULT=YES" }
}
