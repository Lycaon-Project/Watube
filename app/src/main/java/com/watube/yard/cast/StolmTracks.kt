package com.watube.yard.cast

import androidx.annotation.OptIn
import androidx.media3.common.C
import androidx.media3.common.Format
import androidx.media3.common.MimeTypes
import androidx.media3.common.TrackGroup
import androidx.media3.common.Tracks
import androidx.media3.common.util.UnstableApi
import com.watube.yard.api.obj.Subtitle
import com.watube.yard.helpers.PlayerHelper

// region Stolm
/**
 * The tracks of a cast video as the phone's player options show them (quality, audio track,
 * subtitles): the same menus as for the phone, the choice made in them goes to the TV.
 */
@OptIn(UnstableApi::class)
internal object StolmTracks {
    private const val VIDEO_ID = "stolm-video-"
    private const val AUDIO_ID = "stolm-audio-"
    private const val TEXT_ID = "stolm-text-"

    /** 16:9, for the menus: only the height of a picture is listed. */
    private const val WIDTH_PER_HEIGHT = 16.0 / 9.0

    fun of(options: HlsOptions, subtitles: List<Subtitle>, choices: StolmChoices): Tracks {
        val height = HlsMaster.pickHeight(options.heights, choices)
        val audio = HlsMaster.pickAudio(options.audio, choices)
        val video = options.heights.mapIndexed { index, it ->
            Format.Builder()
                .setId("$VIDEO_ID$index")
                .setSampleMimeType(MimeTypes.VIDEO_H264)
                .setHeight(it)
                .setWidth((it * WIDTH_PER_HEIGHT).toInt())
                .build() to (it == height)
        }
        val audioTracks = options.audio.mapIndexed { index, it ->
            Format.Builder()
                .setId("$AUDIO_ID$index")
                .setSampleMimeType(MimeTypes.AUDIO_AAC)
                .setLanguage(it.language)
                .setLabel(it.name)
                .setRoleFlags(if (it.isOriginal) C.ROLE_FLAG_MAIN else C.ROLE_FLAG_DUB)
                .build() to (it == audio)
        }
        val text = castableSubtitles(subtitles).map {
            Format.Builder()
                .setId(textIdOf(it))
                .setSampleMimeType(MimeTypes.TEXT_VTT)
                .setLanguage(it.code)
                .setLabel(it.name)
                .setRoleFlags(roleFlagsOf(it))
                .build() to (it == choices.subtitles)
        }
        // like the phone's player: one group per language, the qualities of the picture together
        val groups = listOf(video).filter { it.isNotEmpty() } + (audioTracks + text).map { listOf(it) }
        return Tracks(groups.map(::group))
    }

    /**
     * The subtitles behind a text track id of [of]; null for none, or for an id of another player.
     * The id names the language and kind, not a position: the screen sends it again for the next
     * video, where the same position may hold another language.
     */
    fun subtitlesOf(trackId: String?, subtitles: List<Subtitle>): Subtitle? {
        if (!isTextTrack(trackId)) return null
        return castableSubtitles(subtitles).firstOrNull { textIdOf(it) == trackId }
    }

    internal fun textIdOf(subtitle: Subtitle) =
        TEXT_ID + (if (subtitle.autoGenerated == true) "auto:" else "") + subtitle.code

    /**
     * Whether [first] and [second] make the TV play the same audio track, quality and subtitles.
     * Without [options] (the master could not be read) only identical choices are.
     */
    fun samePick(options: HlsOptions, first: StolmChoices, second: StolmChoices): Boolean {
        if (first == second) return true
        if (options == HlsOptions.NONE) return false
        return HlsMaster.pickAudio(options.audio, first) == HlsMaster.pickAudio(options.audio, second) &&
            HlsMaster.pickHeight(options.heights, first) == HlsMaster.pickHeight(options.heights, second) &&
            first.subtitles == second.subtitles
    }

    /** Whether [trackId] is one of the text tracks of [of]. */
    fun isTextTrack(trackId: String?) = trackId?.startsWith(TEXT_ID) == true

    /** The role the phone's player gives these subtitles (see [PlayerHelper.getSubtitleRoleFlags]). */
    fun roleFlagsOf(subtitle: Subtitle) =
        if (subtitle.autoGenerated == true) PlayerHelper.ROLE_FLAG_AUTO_GEN_SUBTITLE else C.ROLE_FLAG_CAPTION

    private fun castableSubtitles(subtitles: List<Subtitle>) = subtitles.filter { it.url != null && it.code != null }

    private fun group(formats: List<Pair<Format, Boolean>>) = Tracks.Group(
        TrackGroup(*formats.map { it.first }.toTypedArray()),
        false,
        IntArray(formats.size) { C.FORMAT_HANDLED },
        formats.map { it.second }.toBooleanArray()
    )
}
// endregion
