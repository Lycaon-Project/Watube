package com.watube.yard.helpers

import org.bouncycastle.crypto.generators.Argon2BytesGenerator
import org.bouncycastle.crypto.params.Argon2Parameters
import java.io.ByteArrayOutputStream
import java.io.DataInputStream
import java.io.DataOutputStream
import java.io.EOFException
import java.io.IOException
import java.nio.CharBuffer
import java.security.GeneralSecurityException
import java.security.SecureRandom
import java.text.Normalizer
import javax.crypto.AEADBadTagException
import javax.crypto.Cipher
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

// region Backup & Restore
/**
 * Encrypted backup files: the backup is encrypted with AES-256-GCM, under a key derived from
 * a secret of the user by Argon2id (RFC 9106: 64 MiB, 3 passes, 4 lanes), so that guessing
 * the secret offline costs as much memory and time as possible.
 *
 * The secret is either a password chosen by the user or a recovery code generated by the app.
 * Nothing about it is stored on the phone: without it, the file cannot be read.
 *
 * Layout: `WATUBEBK` | version | secret kind | memory KiB (int) | passes (int) | lanes |
 * salt length | salt | 12 byte IV | ciphertext and tag. Everything before the ciphertext is
 * authenticated with it, so the parameters cannot be altered either.
 */
object BackupCrypto {
    enum class SecretKind(val id: Int) { PASSWORD(1), RECOVERY_CODE(2) }

    /** The secret does not open the file (or the file was altered). */
    class WrongSecretException : GeneralSecurityException("wrong password or recovery code")

    /** Not a backup this version can read, or parameters outside the accepted bounds. */
    class InvalidBackupException(message: String) : IOException(message)

    const val MIN_PASSWORD_LENGTH = 12

    private val MAGIC = "WATUBEBK".toByteArray(Charsets.US_ASCII)
    private const val VERSION = 1
    private const val MEMORY_KIB = 64 * 1024
    private const val PASSES = 3
    private const val LANES = 4
    private const val SALT_BYTES = 16
    private const val IV_BYTES = 12
    private const val KEY_BYTES = 32
    private const val TAG_BITS = 128
    private const val TRANSFORMATION = "AES/GCM/NoPadding"

    // a file is untrusted: costs it may ask for are bounded (memory, time), above what this
    // version writes so that a later one can raise its own
    private const val MAX_MEMORY_KIB = 128 * 1024
    private const val MAX_PASSES = 10
    private const val MAX_LANES = 8
    private val SALT_RANGE = 16..64

    /** Crockford base32: no I, L, O nor U to misread when copying the code by hand */
    private const val CODE_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
    private const val CODE_GROUPS = 6
    private const val CODE_GROUP_LENGTH = 4

    private val random = SecureRandom()

    private class Header(
        val kind: SecretKind,
        val memoryKib: Int,
        val passes: Int,
        val lanes: Int,
        val salt: ByteArray,
        val iv: ByteArray,
        val length: Int
    )

    fun isEncrypted(file: ByteArray): Boolean =
        file.size >= MAGIC.size && file.copyOfRange(0, MAGIC.size).contentEquals(MAGIC)

    /** What the user has to give to open [file]: a password, or a recovery code. */
    fun secretKindOf(file: ByteArray): SecretKind = readHeader(file).kind

    fun encrypt(plain: ByteArray, secret: CharArray, kind: SecretKind): ByteArray {
        val salt = ByteArray(SALT_BYTES).also(random::nextBytes)
        val iv = ByteArray(IV_BYTES).also(random::nextBytes)
        val header = ByteArrayOutputStream().also { bytes ->
            DataOutputStream(bytes).run {
                write(MAGIC)
                writeByte(VERSION)
                writeByte(kind.id)
                writeInt(MEMORY_KIB)
                writeInt(PASSES)
                writeByte(LANES)
                writeByte(salt.size)
                write(salt)
                write(iv)
            }
        }.toByteArray()

        val key = derivedKeyOf(secret, kind, salt, MEMORY_KIB, PASSES, LANES)
        try {
            val cipher = cipher(Cipher.ENCRYPT_MODE, key, iv)
            cipher.updateAAD(header)
            return header + cipher.doFinal(plain)
        } finally {
            key.fill(0)
        }
    }

    fun decrypt(file: ByteArray, secret: CharArray): ByteArray {
        val header = readHeader(file)
        // the derivation holds its whole memory cost in the heap: a file asking for more than
        // this phone can spare is refused rather than crashing the app
        if (header.memoryKib * 1024L > Runtime.getRuntime().maxMemory() / 2) {
            throw InvalidBackupException("key derivation needs more memory than available")
        }
        val key = with(header) { derivedKeyOf(secret, kind, salt, memoryKib, passes, lanes) }
        try {
            val cipher = cipher(Cipher.DECRYPT_MODE, key, header.iv)
            cipher.updateAAD(file, 0, header.length)
            return cipher.doFinal(file, header.length, file.size - header.length)
        } catch (e: AEADBadTagException) {
            throw WrongSecretException()
        } finally {
            key.fill(0)
        }
    }

    /** 120 random bits, as `XXXX-XXXX-XXXX-XXXX-XXXX-XXXX`. */
    fun newRecoveryCode(): CharArray {
        val code = CharArray(CODE_GROUPS * (CODE_GROUP_LENGTH + 1) - 1) { '-' }
        var index = 0
        repeat(CODE_GROUPS) { group ->
            repeat(CODE_GROUP_LENGTH) {
                code[index++] = CODE_ALPHABET[random.nextInt(CODE_ALPHABET.length)]
            }
            if (group < CODE_GROUPS - 1) index++
        }
        return code
    }

    /**
     * A recovery code is typed back loosely: case, spaces and dashes do not matter, and the
     * letters base32 leaves out read as the digits they look like. A password is used as
     * typed, in its composed Unicode form (NFC): an accented letter typed on another keyboard
     * or phone, as a letter plus an accent, must still open the backup.
     */
    private fun prepared(secret: CharArray, kind: SecretKind): CharArray {
        if (kind == SecretKind.PASSWORD) {
            val chars = CharBuffer.wrap(secret)
            return if (Normalizer.isNormalized(chars, Normalizer.Form.NFC)) {
                secret
            } else {
                Normalizer.normalize(chars, Normalizer.Form.NFC).toCharArray()
            }
        }
        return secret.filterNot { it == '-' || it.isWhitespace() }
            .map { char ->
                when (val upper = char.uppercaseChar()) {
                    'O' -> '0'
                    'I', 'L' -> '1'
                    else -> upper
                }
            }
            .toCharArray()
    }

    private fun readHeader(file: ByteArray): Header {
        if (!isEncrypted(file)) throw InvalidBackupException("not an encrypted backup")
        try {
            val input = DataInputStream(file.inputStream(MAGIC.size, file.size - MAGIC.size))
            val version = input.readUnsignedByte()
            if (version != VERSION) throw InvalidBackupException("unsupported version $version")
            val kindId = input.readUnsignedByte()
            val kind = SecretKind.entries.firstOrNull { it.id == kindId }
                ?: throw InvalidBackupException("unknown secret kind")
            val memoryKib = input.readInt()
            val passes = input.readInt()
            val lanes = input.readUnsignedByte()
            val salt = ByteArray(input.readUnsignedByte()).also(input::readFully)
            val iv = ByteArray(IV_BYTES).also(input::readFully)
            val bounded = lanes in 1..MAX_LANES && memoryKib in 8 * lanes..MAX_MEMORY_KIB &&
                passes in 1..MAX_PASSES && salt.size in SALT_RANGE
            if (!bounded) throw InvalidBackupException("key derivation parameters out of bounds")
            val length = MAGIC.size + 2 + 4 + 4 + 1 + 1 + salt.size + IV_BYTES
            if (file.size < length + TAG_BITS / 8) throw InvalidBackupException("truncated backup")
            return Header(kind, memoryKib, passes, lanes, salt, iv, length)
        } catch (e: EOFException) {
            throw InvalidBackupException("truncated backup")
        }
    }

    @Suppress("LongParameterList")
    private fun derivedKeyOf(
        secret: CharArray,
        kind: SecretKind,
        salt: ByteArray,
        memoryKib: Int,
        passes: Int,
        lanes: Int
    ): ByteArray {
        val input = prepared(secret, kind)
        val parameters = Argon2Parameters.Builder(Argon2Parameters.ARGON2_id)
            .withVersion(Argon2Parameters.ARGON2_VERSION_13)
            .withMemoryAsKB(memoryKib)
            .withIterations(passes)
            .withParallelism(lanes)
            .withSalt(salt)
            .build()
        return try {
            ByteArray(KEY_BYTES).also { key ->
                Argon2BytesGenerator().apply { init(parameters) }.generateBytes(input, key)
            }
        } finally {
            // the copy made for a recovery code; a password stays the caller's to clear
            if (input !== secret) input.fill(Char.MIN_VALUE)
        }
    }

    private fun cipher(mode: Int, key: ByteArray, iv: ByteArray): Cipher =
        Cipher.getInstance(TRANSFORMATION).apply {
            init(mode, SecretKeySpec(key, "AES"), GCMParameterSpec(TAG_BITS, iv))
        }
}
